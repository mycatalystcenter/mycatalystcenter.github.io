  const PAGE_SIZE = 24;
  const CONTENT_PAGE_SIZE = 12;
  const MAX_QUERY_LENGTH = 100;
  const MAX_SEARCH_TEXT_LENGTH = 1000;
  const MODULE_SOURCE_BASE =
    "https://github.com/cisco-en-programmability/catalystcenter-ansible/blob/main/plugins/modules/";
  const SAFE_MODULE_NAME = /^[a-z0-9_]+$/;
  const SAFE_CONTENT_KINDS = new Set(["Role", "CVP"]);
  const CONTENT_REPO_PATH = "/cisco-en-programmability/catalystcenter-ansible/blob/main/";
  const ACRONYMS = new Set([
    "aaa", "api", "ap", "ip", "ise", "lan", "pnp", "rf", "rma", "sda", "sdk",
    "snmp", "ssid", "swim", "url", "uuid", "vlan", "vpn", "wan"
  ]);

  function byId(id) {
    return document.getElementById(id);
  }

  function normalized(value, maxLength = MAX_QUERY_LENGTH) {
    return String(value)
      .slice(0, maxLength)
      .normalize("NFKC")
      .trim()
      .toLocaleLowerCase("en-US");
  }

  function queryWords(value) {
    return normalized(value).split(/\s+/).filter(Boolean);
  }

  function matchesAllWords(value, words) {
    const haystack = normalized(value, MAX_SEARCH_TEXT_LENGTH);
    return words.every((word) => haystack.includes(word));
  }

  function humanTitle(name) {
    const words = name.split("_").map((word) => {
      if (ACRONYMS.has(word)) return word.toUpperCase();
      return word;
    });
    const title = words.join(" ");
    return title.charAt(0).toLocaleUpperCase("en-US") + title.slice(1);
  }

  function moduleFamily(name) {
    if (name.endsWith("_workflow_manager")) return "Workflow manager";
    if (name.endsWith("_playbook_config_generator")) return "Config generator";
    if (name.endsWith("_info") || name.includes("_info_")) return "Information module";
    return "API module";
  }

  function moduleCard(name) {
    const link = document.createElement("a");
    const meta = document.createElement("div");
    const family = document.createElement("span");
    const arrow = document.createElement("span");
    const title = document.createElement("h3");
    const code = document.createElement("code");

    link.className = "api-module-card";
    link.href = MODULE_SOURCE_BASE + encodeURIComponent(name) + ".py";
    link.target = "_blank";
    link.rel = "noopener noreferrer";

    meta.className = "api-module-meta";
    family.textContent = moduleFamily(name);
    arrow.textContent = "↗";
    arrow.setAttribute("aria-hidden", "true");
    meta.append(family, arrow);

    title.textContent = humanTitle(name);
    code.textContent = name;

    link.append(meta, title, code);
    return link;
  }

  function safeContentItem(item) {
    if (!item || typeof item !== "object") return false;
    const fields = ["name", "title", "description", "category", "family", "url"];
    if (!fields.every((field) => typeof item[field] === "string" && item[field].length > 0)) return false;
    if (!SAFE_CONTENT_KINDS.has(item.kind) || !SAFE_MODULE_NAME.test(item.name)) return false;
    if (item.title.length > 120 || item.description.length > 500 || item.category.length > 80 || item.family.length > 80) return false;

    try {
      const url = new URL(item.url);
      const directory = item.kind === "Role" ? "roles" : "cvp";
      const expectedPath = `${CONTENT_REPO_PATH}${directory}/${item.name}/readme.md`;
      return url.protocol === "https:"
        && url.hostname === "github.com"
        && url.port === ""
        && url.username === ""
        && url.password === ""
        && url.search === ""
        && url.hash === ""
        && url.pathname.toLocaleLowerCase("en-US") === expectedPath;
    } catch {
      return false;
    }
  }

  function contentSearchText(item) {
    const typeAliases = item.kind === "Role" ? "role reusable" : "cvp playbook validated content";
    return [item.name.replaceAll("_", " "), item.title, item.description, item.category, item.family, typeAliases].join(" ");
  }

  function contentCard(item) {
    const link = document.createElement("a");
    const meta = document.createElement("div");
    const kind = document.createElement("span");
    const category = document.createElement("span");
    const title = document.createElement("h3");
    const description = document.createElement("p");
    const footer = document.createElement("div");
    const identity = document.createElement("code");
    const family = document.createElement("span");

    link.className = "content-resource-card";
    link.href = item.url;
    link.target = "_blank";
    link.rel = "noopener noreferrer";

    meta.className = "content-resource-meta";
    kind.className = `content-kind content-kind-${item.kind.toLocaleLowerCase("en-US")}`;
    kind.textContent = item.kind === "Role" ? "ROLE" : "CVP";
    category.textContent = item.category;
    meta.append(kind, category);

    title.textContent = item.title;
    description.textContent = item.description;

    footer.className = "content-resource-footer";
    identity.textContent = item.name;
    family.textContent = `${item.family} ↗`;
    footer.append(identity, family);

    link.append(meta, title, description, footer);
    return link;
  }

  function bindSearchControls(input, searchButton, clearButton, apply, clear) {
    input.addEventListener("input", apply);
    searchButton.addEventListener("click", apply);
    clearButton.addEventListener("click", clear);
    input.addEventListener("keydown", (event) => {
      if (event.key === "Enter") {
        event.preventDefault();
        apply();
      }
      if (event.key === "Escape") {
        clear();
      }
    });
  }

  function initWorkflowSearch() {
    const input = byId("workflow-search");
    const searchButton = byId("workflow-search-button");
    const clearButton = byId("workflow-search-clear");
    const catalog = byId("workflow-catalog");
    const list = byId("workflow-catalog-list");
    const status = byId("workflow-result-count");
    const empty = byId("workflow-search-empty");
    if (!input || !searchButton || !clearButton || !catalog || !list || !status || !empty) return;

    const items = Array.from(list.querySelectorAll("a"));

    function apply() {
      const words = queryWords(input.value);
      let visible = 0;
      items.forEach((item) => {
        const match = words.length === 0 || matchesAllWords(item.textContent, words);
        item.hidden = !match;
        if (match) visible += 1;
      });
      if (words.length) catalog.open = true;
      status.textContent = words.length
        ? `${visible} of ${items.length} workflow managers match`
        : `${items.length} workflow managers`;
      empty.hidden = visible !== 0;
      clearButton.hidden = words.length === 0;
    }

    function clear() {
      input.value = "";
      apply();
      input.focus();
    }

    bindSearchControls(input, searchButton, clearButton, apply, clear);
    apply();
  }

  function initModuleSearch() {
    const input = byId("module-search");
    const searchButton = byId("module-search-button");
    const clearButton = byId("module-search-clear");
    const list = byId("api-module-list");
    const status = byId("module-result-count");
    const empty = byId("module-search-empty");
    const loadMore = byId("module-load-more");
    if (!input || !searchButton || !clearButton || !list || !status || !empty || !loadMore) return;

    const modules = MODULES.filter((name) => SAFE_MODULE_NAME.test(name));
    let filtered = modules;
    let visibleCount = PAGE_SIZE;

    function render() {
      const visibleModules = filtered.slice(0, visibleCount);
      const fragment = document.createDocumentFragment();
      visibleModules.forEach((name) => fragment.append(moduleCard(name)));
      list.replaceChildren(fragment);

      const shown = Math.min(visibleCount, filtered.length);
      const words = queryWords(input.value);
      status.textContent = words.length
        ? `Showing ${shown.toLocaleString()} of ${filtered.length.toLocaleString()} matching modules`
        : `Showing ${shown.toLocaleString()} of ${modules.length.toLocaleString()} modules`;
      empty.hidden = filtered.length !== 0;
      loadMore.hidden = shown >= filtered.length;
      clearButton.hidden = words.length === 0;
    }

    function apply() {
      const words = queryWords(input.value);
      filtered = words.length
        ? modules.filter((name) => matchesAllWords(name.replaceAll("_", " "), words))
        : modules;
      visibleCount = PAGE_SIZE;
      render();
    }

    function clear() {
      input.value = "";
      apply();
      input.focus();
    }

    loadMore.addEventListener("click", () => {
      const firstNewIndex = visibleCount;
      visibleCount += PAGE_SIZE;
      render();
      list.children[firstNewIndex]?.focus({ preventScroll: true });
    });

    bindSearchControls(input, searchButton, clearButton, apply, clear);
    apply();
  }

  function initContentSearch() {
    const input = byId("content-search");
    const searchButton = byId("content-search-button");
    const clearButton = byId("content-search-clear");
    const list = byId("content-result-list");
    const status = byId("content-result-count");
    const empty = byId("content-search-empty");
    const loadMore = byId("content-load-more");
    const filterButtons = Array.from(document.querySelectorAll("[data-content-kind]"));
    if (!input || !searchButton || !clearButton || !list || !status || !empty || !loadMore || filterButtons.length === 0) return;

    const source = Array.isArray(globalThis.CATALYST_CONTENT_CATALOG)
      ? globalThis.CATALYST_CONTENT_CATALOG
      : [];
    const items = source
      .filter(safeContentItem)
      .slice()
      .sort((left, right) => left.title.localeCompare(right.title, "en-US") || left.kind.localeCompare(right.kind, "en-US"));
    let activeKind = "All";
    let filtered = items;
    let visibleCount = CONTENT_PAGE_SIZE;

    function kindLabel() {
      if (activeKind === "Role") return "roles";
      if (activeKind === "CVP") return "CVPs";
      return "roles and CVPs";
    }

    function render() {
      const visibleItems = filtered.slice(0, visibleCount);
      const fragment = document.createDocumentFragment();
      visibleItems.forEach((item) => fragment.append(contentCard(item)));
      list.replaceChildren(fragment);

      const shown = Math.min(visibleCount, filtered.length);
      const words = queryWords(input.value);
      const label = kindLabel();
      status.textContent = words.length
        ? `Showing ${shown} of ${filtered.length} matching ${label}`
        : `Showing ${shown} of ${filtered.length} ${label}`;
      empty.textContent = `No ${label} match that search.`;
      empty.hidden = filtered.length !== 0;
      loadMore.hidden = shown >= filtered.length;
      clearButton.hidden = words.length === 0;
    }

    function apply() {
      const words = queryWords(input.value);
      filtered = items.filter((item) => {
        const kindMatches = activeKind === "All" || item.kind === activeKind;
        const queryMatches = words.length === 0 || matchesAllWords(contentSearchText(item), words);
        return kindMatches && queryMatches;
      });
      visibleCount = CONTENT_PAGE_SIZE;
      render();
    }

    function clear() {
      input.value = "";
      apply();
      input.focus();
    }

    filterButtons.forEach((button) => {
      button.addEventListener("click", () => {
        const nextKind = button.dataset.contentKind;
        if (nextKind !== "All" && !SAFE_CONTENT_KINDS.has(nextKind)) return;
        activeKind = nextKind;
        filterButtons.forEach((candidate) => {
          candidate.setAttribute("aria-pressed", String(candidate === button));
        });
        apply();
      });
    });

    loadMore.addEventListener("click", () => {
      const firstNewIndex = visibleCount;
      visibleCount += CONTENT_PAGE_SIZE;
      render();
      list.children[firstNewIndex]?.focus({ preventScroll: true });
    });

    bindSearchControls(input, searchButton, clearButton, apply, clear);
    apply();
  }

  initWorkflowSearch();
  initModuleSearch();
  initContentSearch();
